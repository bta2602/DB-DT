// Errors may already be translated by the request wrapper. Resolve them back to
// the source so an open form also updates when the user changes language.
const sourceByTranslation = new Map<string, string>();
for (const [source, translations] of Object.entries(dictionary)) {
  for (const text of translations) {
    if (!sourceByTranslation.has(text)) sourceByTranslation.set(text, source);
  }
}

export function translate(source: string, locale: Locale, values?: TranslationValues): string {
  const key = Object.hasOwn(dictionary, source)
    ? source
    : sourceByTranslation.get(source) || source;
  const entry = Object.hasOwn(dictionary, key) ? dictionary[key] : undefined;
  const translated = locale === 'ru' || !entry ? key : entry[locale === 'kk' ? 0 : 1];
  return values
    ? translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
        Object.hasOwn(values, key) ? String(values[key]) : placeholder,
      )
    : translated;
}
